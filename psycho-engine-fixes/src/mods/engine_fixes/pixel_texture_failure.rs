//! Native texture-consumer containment for the reported NiPixelData OOM.
//!
//! Owned instruction bridges reject NULL before creation/upload/publication or
//! refresh generation stamps. Factories own their unpublished outer objects;
//! the 2D factory additionally holds one native pixel reference. Failure releases
//! exactly those owners through native teardown. Refresh and resolver bridges
//! reuse existing return/unlock epilogues. Successful paths replay the displaced
//! instructions and keep the installed converter and allocator providers.
//!
//! All patches are preflighted and installed in memset's quiescent transaction,
//! before its constructor guard. No worker, TLS owner, configuration or allocator
//! classification is added. Valid paths add bounded register/result checks;
//! failure counters/logs are sampled at powers of two. The executable contracts
//! and untested game integration are recorded in the incident contract document.

