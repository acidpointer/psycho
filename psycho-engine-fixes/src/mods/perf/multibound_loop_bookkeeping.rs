/// Install the six native loop-bookkeeping patches during core activation.
///
/// Requires the quiescent pre-CRT barrier before core initialization completes.
/// Every full owner prefix/suffix and patch window is checked before any write.
/// An exact existing replacement acquires no ownership. Conflicting code or
/// memory/protection failures return an error. Application failure attempts
/// best-effort ownership-aware rollback; restoration failures use the shared
/// logger and foreign writes are never overwritten. Successful patches remain
/// until process exit. No native data is read, FFI bridge is created or gameplay
/// lifecycle work is registered.
pub(crate) fn install() -> Result<()> {
    ensure!(
        crate::entry::has_pre_crt_startup_boundary() && !crate::entry::is_initialized(),
        "Compound loop installation requires core activation at the pre-CRT barrier"
    );
    for signature in OWNER_SIGNATURES {
        signature.verify().with_context(|| signature.name())?;
    }
    for patch in PATCHES {
        patch.verify().with_context(|| patch.name())?;
    }

    let mut transaction = ModificationTransaction::new();
    for patch in PATCHES {
        if let Err(error) = transaction.apply_patch(patch) {
            log::error!(
                "[MULTIBOUND_LOOPS] Installation failed; attempting rollback of owned writes: {error}"
            );
            return Err(error).with_context(|| patch.name());
        }
    }
    transaction.commit();
    log::debug!(
        "[MULTIBOUND_LOOPS] Qualified sites: save=0x{:08X}, restore=0x{:08X}, sphere=0x{:08X}, bound=0x{:08X}, shape=0x{:08X}, portal=0x{:08X}",
        SAVE_PATCH.address(),
        RESTORE_PATCH.address(),
        SPHERE_PATCH.address(),
        BOUND_PATCH.address(),
        SHAPE_PATCH.address(),
        PORTAL_PATCH.address(),
    );
    log::info!("[MULTIBOUND_LOOPS] Compound visibility bookkeeping optimized at six native sites");
    Ok(())
}
