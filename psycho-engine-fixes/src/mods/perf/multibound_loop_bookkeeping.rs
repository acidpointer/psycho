//! Remove redundant native compound-mask and program-loop bookkeeping.
//!
//! Six call-free integer windows forward private-frame values while retaining
//! every engine read/write, local store, outgoing register/flag, native frame,
//! signed bound and call boundary. Save/restore each remove three instructions
//! and three local reads per record; the sphere gate removes one of each; each
//! reached second/third program check removes two instructions and one read.
//! No FP operation, allocation order, callback or engine ownership is changed.
//!
//! Full owner prefixes/suffixes and six patch windows are preflighted before
//! writing at the quiescent pre-CRT activation barrier. One independent
//! transaction rolls back acquired writes best-effort; exact existing patches
//! remain unowned. Successful patches live until exit. No gameplay bridge,
//! input cache, guard, allocation, lock, event handler or diagnostics is added.
//!
//! Native contracts and qualification boundaries are recorded in
//! `docs/fnv_location_performance_static_audit.md`, six-site loop sections.

